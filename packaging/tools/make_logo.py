"""Generates frameforge/resources/logo.svg – a black hole with accretion disk.

Own vector drawing (gradients only, no SVG filters, because Qt's SVG renderer
does not support them). Run: python packaging/tools/make_logo.py
"""

import math
import random
from pathlib import Path

CX, CY = 256, 250          # centre of the black hole
R_HOLE = 66                # shadow radius
TILT = -11                 # disk tilt in degrees
OUT = Path(__file__).resolve().parents[2] / "frameforge" / "resources" / "logo.svg"


def half_annulus(ro, rro, ri, rri, front: bool) -> str:
    """Upper (back) or lower (front) half of an elliptical ring in local coordinates."""
    s1, s2 = (0, 1) if front else (1, 0)
    return (f"M{-ro} 0 A{ro} {rro} 0 0 {s1} {ro} 0 L{ri} 0 "
            f"A{ri} {rri} 0 0 {s2} {-ri} 0 Z")


def half_arc(rx, ry, front: bool) -> str:
    s = 0 if front else 1
    return f"M{-rx} 0 A{rx} {ry} 0 0 {s} {rx} 0"


def streaks(front: bool, rnd: random.Random) -> str:
    """Thin elliptical strokes that give the disk its swirling texture."""
    out = []
    for _ in range(48):
        rx = rnd.uniform(92, 238)
        ry = rx * rnd.uniform(0.17, 0.23) if front else rx * rnd.uniform(0.15, 0.2)
        w = rnd.uniform(0.8, 3.2)
        o = rnd.uniform(0.18, 0.55) * (1.0 if rx < 170 else 0.6)
        col = rnd.choice(["#ffffff", "#d8ecff", "#9cc8ff", "#7a9bea", "#a58fe0"])
        out.append(f'<path d="{half_arc(rx, ry, front)}" fill="none" stroke="{col}" '
                   f'stroke-width="{w:.1f}" stroke-opacity="{o:.2f}"/>')
    return "\n      ".join(out)


def halo_rings() -> str:
    """Lensed image of the far side of the disk: rings around the shadow."""
    rings = [f'<circle cx="{CX}" cy="{CY}" r="158" fill="url(#haloGlow)"/>',
             f'<circle cx="{CX}" cy="{CY}" r="150" fill="url(#haloTint)"/>']
    # fine circular streaks for texture
    rnd = random.Random(7)
    for _ in range(60):
        r = rnd.uniform(74, 150)
        start = rnd.uniform(0, 360)
        span = rnd.uniform(25, 140)
        a0, a1 = math.radians(start), math.radians(start + span)
        x0, y0 = CX + r * math.cos(a0), CY + r * math.sin(a0)
        x1, y1 = CX + r * math.cos(a1), CY + r * math.sin(a1)
        rings.append(f'<path d="M{x0:.1f} {y0:.1f} A{r:.1f} {r:.1f} 0 0 1 {x1:.1f} {y1:.1f}" fill="none" '
                     f'stroke="{rnd.choice(["#ffffff", "#cfe6ff", "#b9b4f0"])}" '
                     f'stroke-width="{rnd.uniform(0.6, 2.2):.1f}" '
                     f'stroke-opacity="{rnd.uniform(0.12, 0.4) * (1.25 - (r - 74) / 150):.2f}"/>')
    return "\n  ".join(rings)


def build() -> str:
    rnd = random.Random(42)
    disk_back = half_annulus(240, 50, 90, 13, front=False)
    disk_front = half_annulus(244, 58, 90, 22, front=True)
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512">
  <!-- FrameForge logo: black hole with accretion disk (generated by packaging/tools/make_logo.py) -->
  <defs>
    <radialGradient id="glow" cx="0.5" cy="0.49" r="0.5">
      <stop offset="0.25" stop-color="#5d8cff" stop-opacity="0.35"/>
      <stop offset="1" stop-color="#1c2a66" stop-opacity="0"/>
    </radialGradient>
    <radialGradient id="haloGlow" cx="0.5" cy="0.5" r="0.5">
      <stop offset="0.40" stop-color="#ffffff"/>
      <stop offset="0.47" stop-color="#e4f2ff"/>
      <stop offset="0.58" stop-color="#9cc3ff" stop-opacity="0.8"/>
      <stop offset="0.74" stop-color="#6f86de" stop-opacity="0.42"/>
      <stop offset="0.90" stop-color="#5a4fa8" stop-opacity="0.14"/>
      <stop offset="1" stop-color="#3a3580" stop-opacity="0"/>
    </radialGradient>
    <linearGradient id="haloTint" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0.5" stop-color="#d9a3e0" stop-opacity="0"/>
      <stop offset="0.8" stop-color="#d9a3e0" stop-opacity="0.32"/>
      <stop offset="1" stop-color="#b07ad0" stop-opacity="0.1"/>
    </linearGradient>
    <linearGradient id="doppler" x1="0" y1="0" x2="1" y2="0">
      <stop offset="0" stop-color="#ffffff" stop-opacity="0"/>
      <stop offset="0.3" stop-color="#ffffff" stop-opacity="0.35"/>
      <stop offset="0.5" stop-color="#ffffff" stop-opacity="0.1"/>
      <stop offset="1" stop-color="#ffffff" stop-opacity="0"/>
    </linearGradient>
    <linearGradient id="disk" x1="0" y1="0" x2="1" y2="0">
      <stop offset="0" stop-color="#3b4f9a" stop-opacity="0"/>
      <stop offset="0.16" stop-color="#4a63b8" stop-opacity="0.65"/>
      <stop offset="0.36" stop-color="#9cc4ff" stop-opacity="0.95"/>
      <stop offset="0.5" stop-color="#ffffff"/>
      <stop offset="0.64" stop-color="#a9cdff" stop-opacity="0.95"/>
      <stop offset="0.84" stop-color="#5a6fc4" stop-opacity="0.7"/>
      <stop offset="1" stop-color="#3b4f9a" stop-opacity="0"/>
    </linearGradient>
    <linearGradient id="diskFront" x1="0" y1="0" x2="1" y2="0">
      <stop offset="0" stop-color="#2c3a78" stop-opacity="0"/>
      <stop offset="0.18" stop-color="#3d509a" stop-opacity="0.8"/>
      <stop offset="0.38" stop-color="#8fb6f5"/>
      <stop offset="0.5" stop-color="#f2f8ff"/>
      <stop offset="0.62" stop-color="#9cc0f5"/>
      <stop offset="0.82" stop-color="#4659a8" stop-opacity="0.85"/>
      <stop offset="1" stop-color="#2c3a78" stop-opacity="0"/>
    </linearGradient>
    <linearGradient id="photon" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#ffffff"/>
      <stop offset="0.5" stop-color="#d6ebff"/>
      <stop offset="1" stop-color="#ffffff" stop-opacity="0.4"/>
    </linearGradient>
  </defs>
  <circle cx="{CX}" cy="{CY}" r="230" fill="url(#glow)"/>
  <!-- lensed far side of the disk (halo above and below the shadow) -->
  {halo_rings()}
  <!-- far half of the accretion disk (behind the hole) -->
  <g transform="translate({CX} {CY}) rotate({TILT})">
    <path d="{disk_back}" fill="url(#disk)" fill-opacity="0.75"/>
    <g>
      {streaks(False, rnd)}
    </g>
  </g>
  <!-- event horizon shadow and photon ring -->
  <circle cx="{CX}" cy="{CY}" r="{R_HOLE}" fill="#000000"/>
  <circle cx="{CX}" cy="{CY}" r="{R_HOLE + 2}" fill="none" stroke="url(#photon)" stroke-width="3"/>
  <!-- near half of the accretion disk (in front of the hole) -->
  <g transform="translate({CX} {CY}) rotate({TILT})">
    <path d="{disk_front}" fill="url(#diskFront)"/>
    <g>
      {streaks(True, rnd)}
    </g>
    <path d="{disk_front}" fill="url(#doppler)"/>
    <path d="{half_arc(90, 22, True)}" fill="none" stroke="#ffffff" stroke-width="3" stroke-opacity="0.95"/>
  </g>
</svg>
'''


if __name__ == "__main__":
    OUT.write_text(build(), encoding="utf-8")
    print(f"geschrieben: {OUT}")
